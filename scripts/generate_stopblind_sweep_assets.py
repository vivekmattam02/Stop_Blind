#!/usr/bin/env python3
"""Write the StopBlind camera-ready's sweep table from the committed analysis output.

    python3 scripts/generate_stopblind_sweep_assets.py \
        [--analysis artifacts/torch/analysis_v1/analysis_main.json] \
        [--out paper/tables/native_c0_sweep.tex]

One cell per run and saved update: the policy's STOP presses on the 61 main episodes, with its
oracle successes in parentheses; bold marks the selection rule's pick. Successes are stated in the
caption, because every trained cell is 0. Nothing is typed by hand: every number comes from
`per_policy_outcomes` and `picks.A` of the analysis output, and the script refuses an output that
does not hold 37 completed policies.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

RUNS = (
    ("Unweighted", "20260825", "unweighted_s20260825", "uw25"),
    ("", "20260826", "unweighted_s20260826", "uw26"),
    ("", "20260827", "unweighted_s20260827", "uw27"),
    ("Weighted", "20260825", "inverse_frequency_s20260825", "wt25"),
    ("", "20260826", "inverse_frequency_s20260826", "wt26"),
    ("", "20260827", "inverse_frequency_s20260827", "wt27"),
)
UPDATES = (32, 64, 96, 128, 160, 192)
UNTRAINED = "unweighted_s20260825_u000"


def _cp_upper_two_sided(k: int, n: int, alpha: float = 0.05) -> float:
    """Exact Clopper-Pearson upper limit, two-sided 95%: P(X <= k) = alpha/2, by bisection."""
    from math import comb

    lo, hi = 0.0, 1.0
    for _ in range(200):
        mid = (lo + hi) / 2
        cdf = sum(comb(n, i) * mid**i * (1 - mid) ** (n - i) for i in range(k + 1))
        lo, hi = (mid, hi) if cdf > alpha / 2 else (lo, mid)
    return (lo + hi) / 2


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--analysis", type=Path,
                    default=Path("artifacts/torch/analysis_v1/analysis_main.json"))
    ap.add_argument("--out", type=Path,
                    default=Path("paper/tables/native_c0_sweep.tex"))
    args = ap.parse_args()
    analysis = json.loads(args.analysis.read_text(encoding="utf-8"))
    outcomes = analysis["per_policy_outcomes"]
    picks = analysis["picks"]["A"]
    if len(outcomes) != 37 or any(v["completed_episodes"] != 61 for v in outcomes.values()):
        raise SystemExit("the analysis does not hold 37 policies with 61 completed episodes each")
    trained_successes = sum(v["Y1"] for k, v in outcomes.items() if k != UNTRAINED)
    if trained_successes != 0:
        raise SystemExit("a trained policy succeeds; this table's caption says none does")
    u0 = outcomes[UNTRAINED]
    bounds = analysis["descriptive"]["family_upper_bound_95"]["per_policy"]
    trained_bounds = {v for k, v in bounds.items() if k != UNTRAINED}
    if len(trained_bounds) != 1:
        raise SystemExit("the trained checkpoints' family bounds differ; the caption gives one")
    fam = trained_bounds.pop()
    u0fam = bounds[UNTRAINED]
    one = _cp_upper_two_sided(0, 61)
    rows = []
    for label, seed, prefix, tag in RUNS:
        cells = []
        for update in UPDATES:
            v = outcomes[f"{prefix}_u{update:03d}"]
            cell = f"{v['Y3']} ({v['Y2']})"
            if picks[tag] == update:
                cell = f"\\textbf{{{cell}}}"
            cells.append(cell)
        rows.append(f"{label} & {seed} & " + " & ".join(cells) + " \\\\")
        if tag == "uw27":
            rows.append("\\midrule")
    src = args.analysis.as_posix()
    lines = [
        f"% Generated by scripts/generate_stopblind_sweep_assets.py from {src}; do not edit.",
        "\\begin{table}[t]",
        "\\centering",
        "\\small",
        "\\caption{Every saved checkpoint executed on the 61 main episodes on NVIDIA L40S GPUs:",
        "\\textsc{stop} presses, with oracle successes in parentheses. Bold: the selection rule's "
        "pick, re-run",
        "here. Every trained checkpoint succeeds in $0/61$ episodes: exact two-sided $95\\%$ "
        "interval",
        f"$0$--${100 * one:.1f}\\%$ for one checkpoint alone, and at most ${100 * fam:.1f}\\%$ "
        "when all 37 are bounded together",
        "(one-sided, Bonferroni). Update 0, one untrained model shared by all six runs, "
        "succeeds in",
        f"${u0['Y1']}/61$ (bounded together: at most ${100 * u0fam:.1f}\\%$), enters the radius "
        f"in {u0['Y2']} and presses",
        f"\\textsc{{stop}} {u0['Y3']} times.}}",
        "\\label{tab:sweep}",
        "\\begin{tabular}{@{}llrrrrrr@{}}",
        "\\toprule",
        " & & \\multicolumn{6}{c}{Update} \\\\",
        "\\cmidrule(l){3-8}",
        "Treatment & Seed & 32 & 64 & 96 & 128 & 160 & 192 \\\\",
        "\\midrule",
        *rows,
        "\\bottomrule",
        "\\end{tabular}",
        "\\end{table}",
    ]
    table = "\n".join(lines) + "\n"
    args.out.write_text(table, encoding="utf-8")
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
