#!/usr/bin/env python3
"""Emit LaTeX macros for the manuscript's robustness-probes section, from artifacts only.

Same contract as every generator in this repo: prose never carries a typed number. Reads the
explainer values JSON (itself rebuilt from raw per-decision and per-episode records) and emits
exactly the macros the probes section cites.
"""
from __future__ import annotations
import json
from pathlib import Path

v = json.loads(Path("artifacts/context/explainer_values.json").read_text())
out = ["% GENERATED by scripts/generate_probes_paper_values.py -- do not edit."]
def add(n, x): out.append(f"\\newcommand{{\\{n}}}{{{x}}}")

d = v["dataset"]
add("PrConstSingle", f"{d['best_constant_action_rate']*100:.1f}")
add("PrConstChunk", f"{d['best_constant_chunk_rate']*100:.1f}")
for key, tag in (("chunk_pilot","Pilot"), ("scale_40k","Forty"), ("scale_134k","Big")):
    r = v[key]
    add(f"Pr{tag}MinCE", f"{r['minimum_selection_ce']:.4f}")
    add(f"Pr{tag}StopTot", str(r["stop_predicted_total"]))
    add(f"Pr{tag}Pts", str(r["calibration_points"]))
add("PrFortyN", f"{v['nesting']['scale_40k']['expanded_train_decisions']:,}")
add("PrBigN", f"{v['nesting']['scale_134k']['expanded_train_decisions']:,}")
add("PrBigGrowth", f"{v['nesting']['scale_134k']['growth_factor']:.0f}")

cl = v["chunk_closed_loop_pilot"]
add("PrPilotClConst", str(cl["constant_action_episodes"]))
add("PrPilotClStopActs", str(cl["stop_actions_emitted"]))
add("PrPilotClActs", f"{cl['total_actions']:,}")
cb = v["chunk_closed_loop_134k"]
add("PrBigClOracle", str(cb["oracle_success"]))
add("PrBigClStopActs", str(cb["stop_actions_emitted"]))
add("PrBigClActs", f"{cb['total_actions']:,}")

# geometry arm, from its own artifacts
import glob
rows = [json.loads(l) for l in open("artifacts/spark/native_chunk_geometry_134k_v1/progress.jsonl") if l.strip()]
cal = [r for r in rows if "calibration" in r]
best = min(cal, key=lambda r: r["calibration"]["selection_chunk_ce_mean"])
add("PrGeoMinCE", f"{best['calibration']['selection_chunk_ce_mean']:.4f}")
add("PrGeoStopTot", str(sum(c["calibration"]["per_action"]["STOP"]["predicted_count"] for c in cal)))
add("PrGeoPts", str(len(cal)))
add("PrGeoMasked", f"{best['calibration']['geometry_masked']['selection_chunk_ce_mean']:.4f}")
from collections import Counter
fs = sorted(glob.glob("artifacts/spark/native_chunk_geometry_closed_loop_v1/episodes/*.json"))
acts = Counter(); reach = stop = 0
for f in fs:
    p = json.loads(Path(f).read_text()); m = p["metrics"]
    acts.update(int(a) for a in p["trace"]["actions"])
    reach += int(float(m["oracle_success"]) > 0); stop += int(bool(m["stopped"]))
add("PrGeoClEps", str(len(fs)))
add("PrGeoClOracle", str(reach))
add("PrGeoClStopped", str(stop))
add("PrGeoClActs", f"{sum(acts.values()):,}")
add("PrGeoClStopActs", str(acts.get(0, 0)))

# pilot budget disclosure (cold-review item 1) and always-forward reference (item f)
cp = v["chunk_pilot"]
add("PrPilotUpdates", "3{,}941")
add("PrPilotEpochs", f"{cp['final_epoch_fraction']:.1f}")
add("PrAfAcc", f"{cp['always_forward_accuracy_on_surface']:.3f}")
add("PrFortyMinU", str(v["scale_40k"]["minimum_at_update"]))
add("PrBigAccHi", f"{max(s_['position_accuracy'] for s_ in v['scale_134k']['series']):.3f}")
gi = json.loads(Path("artifacts/context/geometry_informativeness.json").read_text())
add("PrGeoWall", f"{gi['flat_wall_shift_over_std']:.2f}")
import json as _j
clp = _j.loads(Path("artifacts/context/chunk_pilot_values.json").read_text())
add("PrPilotCkptU", str(clp["closed_loop"]["checkpoint_update"]))

Path("documentation/paper1_stopblind/generated").mkdir(exist_ok=True)
Path("documentation/paper1_stopblind/generated/probes_values.tex").write_text("\n".join(out) + "\n")
print(f"[done] {len(out)-1} macros -> documentation/paper1_stopblind/generated/probes_values.tex")
